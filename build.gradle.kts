import org.gradle.language.jvm.tasks.ProcessResources

plugins {
    `java-library`
    eclipse
    idea
    `maven-publish`
    // Declarados aqui (apply false) para ficarem no classpath; cada loader-*.gradle aplica o seu.
    id("net.neoforged.gradle.userdev") version "7.1.39" apply false
    id("net.minecraftforge.gradle") version "7.0.40" apply false
}

val mod_loader: String by project

// Constante usada nos comentários //? if neoforge / //? if forge do código-fonte.
stonecutter {
    constants.match(mod_loader, "neoforge", "forge")
}

// Plugin do loader, runs e dependências ficam em loader-<mod_loader>.gradle.kts.
apply(from = rootProject.file("loader-$mod_loader.gradle"))

val mod_id: String by project
val mod_name: String by project
val mod_license: String by project
val mod_version: String by project
val mod_group_id: String by project
val mod_authors: String by project
val mod_description: String by project
val minecraft_version: String by project
val minecraft_version_range: String by project
val loader_version_range: String by project
val jei_version: String by project
val jade_version: String by project
val patchouli_version: String by project
val neo_version: String? by project
val neo_version_range: String? by project
val forge_version: String? by project
val forge_version_range: String? by project


if (project == rootProject) {
    // Use Wrapper.DistributionType.ALL para baixar as fontes do Gradle (documentação no IntelliJ).
    tasks.named<Wrapper>("wrapper") {
        distributionType = Wrapper.DistributionType.BIN
    }
}

version = mod_version
group = mod_group_id

repositories {
    mavenLocal()
    mavenCentral()
    maven("https://libraries.minecraft.net")
    maven("https://maven.minecraftforge.net")
    maven("https://maven.blamejared.com")
    maven("https://api.modrinth.com/maven")
}

base {
    archivesName.set("Fartura_v${mod_version}_${mod_loader}_mc${minecraft_version}")
}

// A versão já está no nome do arquivo, então não a repete no sufixo.
tasks.withType<AbstractArchiveTask>().configureEach {
    archiveVersion.set("")
}

// Mojang ships Java 21 to end users starting in 1.20.5, so mods should target Java 21.
java.toolchain.languageVersion.set(JavaLanguageVersion.of(21))

// Include resources generated by data generators.
sourceSets.main {
    resources.srcDir(rootProject.file("src/generated/resources"))
}

// Compila as fontes pré-processadas pelo Stonecutter (não o src/main/java bruto com as diretivas //?).
sourceSets.main {
    java.setSrcDirs(listOf(layout.buildDirectory.dir("generated/stonecutter/main/java").get().asFile))
    // Shim de API do NeoForge sobre o Forge; não passa pelo Stonecutter.
    if (mod_loader == "forge") {
        java.srcDir(rootProject.file("src/forge/java"))
        // Biome modifiers do Forge (forge:add_features); o NeoForge usa a pasta neoforge/.
        resources.srcDir(rootProject.file("src/forge/resources"))
    }
}

// No Forge, o arquivo de src/forge substitui o original (mesmo caminho): exclui as cópias que não são do Forge para evitar duplicata.
if (mod_loader == "forge") {
    val forgeResources = rootProject.file("src/forge/resources")
    tasks.named<ProcessResources>("processResources") {
        exclude { element ->
            !element.isDirectory &&
                !element.file.startsWith(forgeResources) &&
                File(forgeResources, element.relativePath.pathString).exists()
        }
    }
    // Guia (Patchouli) é só NeoForge: receita, tag, item e livros não entram no jar do Forge.
    tasks.named<ProcessResources>("processResources") {
        exclude { element ->
            val p = element.relativePath.pathString
            p.startsWith("data/fartura/patchouli_books") ||
                p.startsWith("assets/fartura/patchouli_books") ||
                p == "data/fartura/recipe/guide.json" ||
                p == "data/fartura/tags/item/guide_ingredients.json" ||
                p == "assets/fartura/models/item/guide.json" ||
                p == "assets/fartura/textures/item/guide.png"
        }
    }
}
if (mod_loader == "forge") {
    tasks.named<Jar>("jar") {
        manifest {
            attributes("MixinConfigs" to "fartura.mixins.json")
        }
    }
}

// Stonecutter gera as fontes de cada versão antes da compilação e da criação dos artefatos do Minecraft.
tasks.matching { it.name == "createMinecraftArtifacts" || it.name == "compileJava" }.configureEach {
    dependsOn("stonecutterGenerate")
}

// Sets up a dependency configuration called 'localRuntime'.
// This configuration should be used instead of 'runtimeOnly' to declare
// a dependency that will be present for runtime testing but that is
// "optional", meaning it will not be pulled by dependents of this mod.
configurations {
    val localRuntime = maybeCreate("localRuntime")
    named("runtimeClasspath") {
        extendsFrom(localRuntime)
    }
}

// This block of code expands all declared replace properties in the specified resource targets.
// A missing property will result in an error. Properties are expanded using ${} notation.
tasks.withType<ProcessResources>().configureEach {
    val replaceProperties = mapOf(
        "minecraft_version" to minecraft_version,
        "minecraft_version_range" to minecraft_version_range,
        "neo_version" to (neo_version ?: ""),
        "neo_version_range" to (neo_version_range ?: ""),
        "forge_version" to (forge_version ?: ""),
        "forge_version_range" to (forge_version_range ?: ""),
        "loader_version_range" to loader_version_range,
        "mod_id" to mod_id,
        "mod_name" to mod_name,
        "mod_license" to mod_license,
        "mod_version" to mod_version,
        "mod_authors" to mod_authors,
        "mod_description" to mod_description
    )
    inputs.properties(replaceProperties)

    // Cada loader só leva o seu próprio arquivo de metadados.
    exclude(if (mod_loader == "neoforge") "META-INF/mods.toml" else "META-INF/neoforge.mods.toml")

    filesMatching(listOf("META-INF/neoforge.mods.toml", "META-INF/mods.toml")) {
        expand(replaceProperties)
    }
}


// Example configuration to allow publishing using the maven-publish plugin
publishing {
    publications {
        register<MavenPublication>("mavenJava") {
            from(components["java"])
        }
    }
    repositories {
        maven {
            url = file("repo").toURI()
        }
    }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
}

// IDEA no longer automatically downloads sources/javadoc jars for dependencies, so we need to explicitly enable the behavior.
idea {
    module {
        isDownloadSources = true
        isDownloadJavadoc = true
    }
}
